from enum import StrEnum


class PaymentStatus(StrEnum):
    """Единый статус платёжной транзакции.

    Общий для `api/payment` (хранение в БД) и `bot/payment` (провайдер,
    обработка вебхуков) — раньше в проекте было три одноимённых класса
    `PaymentStatus` с разными значениями (разный регистр, разный состав
    членов), и совпадение между ними не гарантировалось ничем, кроме
    случайности импорта.

    Значения — нижний регистр, членов четыре (включая `CANCELED`, которого
    не было в провайдерском варианте). Регистр значений не влияет на
    хранение в Postgres: `SQLAlchemy Enum` по умолчанию сериализует в БД
    **имя** члена (`PENDING`), а не его `value` — смена регистра значений
    не требует миграции существующих строк.

    Attributes
        PENDING: Платёж создан, но ещё не завершён.
        PAID: Платёж успешно завершён.
        FAILED: Платёж не прошёл.
        CANCELED: Платёж отменён.

    """

    PENDING = "pending"
    PAID = "paid"
    FAILED = "failed"
    CANCELED = "canceled"
