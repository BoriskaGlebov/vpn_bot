"""Справочник «нода → страна», общий для bot/ и api/.

Раньше одна и та же карта node_name → страна дублировалась в
`bot/utils/formatting.py` и `api/vpn/locations.py` — два места для одного и
того же факта. Источник истины теперь один, здесь.

Флаг сюда намеренно не входит: у `bot/` он приходит динамически из
`settings_bot.vpn.nodes[node_name].flag` (настраивается в `app_config*.toml`
без правок кода), а `api/` к этой секции настроек бота доступа не имеет
(см. `api/vpn/locations.py`) — свести два источника флага в один значило бы
либо захардкодить то, что у `bot/` сейчас конфигурируемо, либо не иметь
флага у `api/` вовсе. Разошлись — пусть разойдутся явно, а не молча.
"""

NODE_COUNTRY_NAMES: dict[str, str] = {
    "de": "Германия (Франкфурт)",
    "fr": "Франция (Париж)",
    "fi": "Финляндия",
    "sof": "Болгария (София)",
    "waw": "Польша (Варшава)",
}


def resolve_country_name(node_name: str | None, default: str) -> str:
    """Определяет название страны ноды по её имени.

    Args:
        node_name (str | None): Имя ноды (ключ `settings_bot.vpn.nodes`)
            либо None.
        default (str): Значение для неизвестной или отсутствующей ноды.
            Не зафиксировано константой здесь: `bot/` и `api/` используют
            разные дефолты (`location_prefix` ноды против "—"), это выбор
            конкретного потребителя, а не общего справочника.

    Returns
        str: Название страны, либо `default`.

    """
    if node_name is None:
        return default
    return NODE_COUNTRY_NAMES.get(node_name, default)
